# shellcheck shell=bash
# shellcheck disable=SC2154 # RESULTS, WORK, versions and timings come from run.sh
# Renders the run's results as docs/src/parity.md.

GROUP_ORDER=(launch commands identity input tools session agents gaps perf)
declare -A GROUP_TITLE=(
  [launch]="Launch and resume"
  [commands]="Built-in commands, exercised"
  [identity]="Session name and colour (/rename, /color)"
  [input]="Input"
  [tools]="Tools, permissions and extensions"
  [session]="Session info"
  [agents]="Agents (the session registry)"
  [gaps]="Known gaps"
  [perf]="Performance"
)

# md_cell: escape table pipes, and angle brackets outside code spans so that
# "<id>" or a raw "<command-name>" record is shown rather than read as HTML.
md_cell() {
  perl -pe 's/(`[^`]*`)|([<>])/defined $1 ? $1 : ($2 eq "<" ? "&lt;" : "&gt;")/ge; s/\|/\\|/g' <<<"$1"
}

status_cell() {
  case $1 in
    PASS) echo "PASS" ;;
    FAIL) echo "**FAIL**" ;;
    GAP) echo "**GAP**" ;;
    SKIP) echo "SKIP" ;;
    *) echo "$1" ;;
  esac
}

# ordered_results: result rows in check-definition order (a --keep run appends
# its rows at the end of results.tsv).
ordered_results() {
  local id
  for id in "${CHECK_IDS[@]}"; do
    awk -F'\t' -v id="$id" '$1 == id' "$RESULTS" | tail -1
  done
}

# write_perf_table: one row per metric with the three targets side by side.
write_perf_table() {
  local id status ev m tv bv sv unit
  cat <<EOF
Measured without model turns on the same machine: the claude-rs build under
test, the installed claude-rs release as the
regression baseline, and the stock Claude Code TUI run directly. claude-rs
always runs the stock binary as its session engine, so its memory and idle
CPU are claude-rs + the Bun bridge + the stock child (and the MCP servers that
child starts, as stock's own tree does), while its rendering and input path
are its own. Resume rendering uses a synthetic 400-record transcript generated
offline in the isolated config; it does not bill a model turn. **FAIL** means
the build under test is more than 10% (plus a small absolute slack) worse than
stock or the installed baseline. Timings depend on machine load, which the
notes record.

| Metric | claude-rs under test ($RS_VERSION) | claude-rs baseline ($BASE_VERSION) | Claude Code $CC_VERSION | Reading | Notes |
| --- | --- | --- | --- | --- | --- |
EOF
  while IFS=$'\t' read -r id status ev; do
    [[ ${CHECK_GROUP[$id]:-} == perf ]] || continue
    m=${id#perf.}
    IFS=$'\t' read -r _ tv bv sv unit < <(awk -F'\t' -v m="$m" '$1 == m' "$WORK/perf.tsv" | tail -1)
    printf '| %s (%s) | %s | %s | %s | %s | `%s` %s |\n' \
      "$(md_cell "${CHECK_NAME[$id]}")" "$(md_cell "${CHECK_STOCK[$id]}")" \
      "${tv:-n/a} $unit" "${bv:-n/a} $unit" "${sv:-n/a} $unit" "$(status_cell "$status")" "$id" "$(md_cell "$ev")"
  done < <(ordered_results)
  printf '\n'
}

group_has_results() {
  local id _rest
  while IFS=$'\t' read -r id _rest; do
    [[ ${CHECK_GROUP[$id]:-} == "$1" ]] && return 0
  done <"$RESULTS"
  return 1
}

write_report() {
  local out=$1 id status ev g counts partial=""
  ((${#ONLY[@]})) && partial=" (partial run: --only ${ONLY[*]})"
  counts=$(awk -F'\t' '{n[$2]++} END {printf "%d PASS, %d FAIL, %d GAP, %d SKIP", n["PASS"], n["FAIL"], n["GAP"], n["SKIP"]}' "$RESULTS")
  mkdir -p "$(dirname "$out")"
  {
    cat <<'EOF'
# Claude Code Parity

This page compares claude-rs with the stock Claude Code TUI it runs on, one
functionality per row. It is generated by the end-to-end parity suite in
`scripts/e2e-parity/`, which drives claude-rs in a private tmux server against
the real, logged-in stock Claude Code (Haiku for every model turn) and reads
the screen, the session registry (`claude agents --json`), transcripts and the
files a turn writes. Do not edit the tables by hand; re-run the suite.

| Reading | Meaning |
| --- | --- |
| PASS | claude-rs does what stock Claude Code does. |
| **FAIL** | claude-rs attempts it but the result differs from stock. |
| **GAP** | Stock Claude Code has it; claude-rs does not (yet). |
| SKIP | Not exercised by the suite; the note says why. |

## Running the suite

The suite needs tmux, jq, node, a logged-in Claude Code and a claude-rs build.
It is local and opt-in: it is never run in CI. A full run takes a few minutes
and spends well under a dollar of Haiku usage.

```sh
# The installed release (its bridge and runtime ship next to the binary):
scripts/e2e-parity/run.sh --report docs/src/parity.md

# A source build:
cargo build && npm run build --prefix agent-sdk
scripts/e2e-parity/run.sh --bin target/debug/claude-rs \
  --bridge agent-sdk/dist/bridge.js --report docs/src/parity.md

# One check, or one group:
scripts/e2e-parity/run.sh --only cmd.model
scripts/e2e-parity/run.sh --only 'agents.*'
```

Set `PARITY_CONFIG_DIR` to a logged-in, isolated config directory before
running these commands. The suite refuses the owner's real Claude profiles.

See `scripts/e2e-parity/README.md` for the options and the safety rules.

EOF
    printf '## Last run\n\n'
    printf -- '- Date: %s\n' "$(date -u '+%Y-%m-%d %H:%M UTC')"
    printf -- '- claude-rs: %s\n' "$RS_VERSION"
    printf -- '- Tested binary: `%s`\n' "$BIN"
    printf -- '- Source checkout revision: `%s`\n' "$SRC_REV"
    printf -- '- Installed baseline binary: `%s`\n' "$BASE_BIN"
    printf -- '- Claude Code: %s\n' "$CC_VERSION"
    printf -- '- Results: %s%s\n' "$counts" "$partial"
    printf -- '- Duration: %ss of checks; TUI Usage subtotal: $%s (excludes the background fixture)\n\n' "$TOTAL_ELAPSED" "$COST"

    for g in "${GROUP_ORDER[@]}"; do
      group_has_results "$g" || continue
      printf '## %s\n\n' "${GROUP_TITLE[$g]}"
      if [[ $g == perf ]]; then
        write_perf_table
        continue
      fi
      if [[ $g == gaps ]]; then
        printf 'Gaps the fork already knew about, confirmed against the binary. The status\nline is under Session info.\n\n'
      fi
      printf '| Functionality | Claude Code | claude-rs (fork) | Evidence / notes |\n'
      printf '| --- | --- | --- | --- |\n'
      while IFS=$'\t' read -r id status ev; do
        [[ ${CHECK_GROUP[$id]:-} == "$g" ]] || continue
        printf '| %s | %s | %s | `%s` %s |\n' \
          "$(md_cell "${CHECK_NAME[$id]}")" "$(md_cell "${CHECK_STOCK[$id]}")" \
          "$(status_cell "$status")" "$id" "$(md_cell "$ev")"
      done < <(ordered_results)
      printf '\n'
    done

    if [[ -s $WORK/inventory.tsv ]]; then
      cat <<'EOF'
## Built-in command inventory

Every stock built-in slash command, classified for claude-rs: **app-owned**
(claude-rs implements it, `src/app/slash/catalog.rs`), **forwarded** (the
stock child advertises it over the SDK and claude-rs passes it through), an
app **equivalent** under another name or key, or **stock-only** (typing it in
claude-rs reports it as not supported). Forwarded commands run inside the
stock child; their output appears only where claude-rs renders it.

| Command | Stock type | claude-rs | Note |
| --- | --- | --- | --- |
EOF
      while IFS=$'\t' read -r name kinds class note; do
        printf '| `/%s` | %s | %s | %s |\n' "$name" "$kinds" "$class" "$(md_cell "$note")"
      done <"$WORK/inventory.tsv"
      printf '\n'
    fi
  } >"$out"
}
